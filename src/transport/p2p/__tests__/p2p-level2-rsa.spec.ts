/**
 * Level-2 negotiation over an RSA cipher: a `get_ciphers` answer with an empty `ecc_private_key` and an
 * RSA `private_key`, whose station sends the 16-byte level-2 key RSA-encrypted (PKCS#1 v1.5) in
 * `CMD_GATEWAYINFO`: the app's sign mode 2, where that key seals every send AES-128-ECB at version byte 1 and
 * sign byte 2 and opens every sign-2 frame (`sendP2PSessionCommand`, `P2PSessionReceiver::decryptNotifyData`).
 *
 * Every key here is generated by the spec; the serial and DID are synthetic.
 */
const STATION_SN = "T8790P0000000001";
const P2P_DID = "XXXXXXX-000000-XXXXX";
const ACCOUNT_ID = "0".repeat(40);
const CIPHER_ID = 10;
/** A 16-character key, the C string the app reads (synthetic). */
const SESSION_KEY = Buffer.from("0123456789abcdef", "latin1");

const { privateKey, publicKey } = generateKeyPairSync("rsa", { modulusLength: 1024 });
const PKCS8_B64 = privateKey.export({ type: "pkcs8", format: "der" }).toString("base64");

/** `cipher_id(2 LE) ‖ 0000 ‖ ciphertext ‖ 00 ‖ trailing bytes`, the decrypted gateway-info layout. */
function gatewayInfo(ciphertext: Buffer, cipherId = CIPHER_ID): Buffer {
  const head = Buffer.alloc(4);
  head.writeUInt16LE(cipherId, 0);
  return Buffer.concat([head, ciphertext, Buffer.from([0x00]), Buffer.alloc(11, 0x5a)]);
}

/** The session key under PKCS#1 v1.5 encryption padding, as the station sends it. */
function wrapped(key: Buffer = SESSION_KEY): Buffer {
  return publicEncrypt({ key: publicKey, padding: constants.RSA_PKCS1_PADDING }, key);
}

/** A raw RSA block (no padding applied), for shaping a malformed padding. */
function rawBlock(block: Buffer): Buffer {
  return publicEncrypt({ key: publicKey, padding: constants.RSA_NO_PADDING }, block);
}

describe("deriveLevel2KeyFromRsaGatewayInfo", () => {
  test("recovers the 16-byte key with a base64 PKCS#8 DER private key", () => {
    expect(deriveLevel2KeyFromRsaGatewayInfo(wrapped(), PKCS8_B64)).toEqual(SESSION_KEY);
  });

  test("recovers the 16-byte key with a PEM private key, PKCS#8 or PKCS#1", () => {
    for (const type of ["pkcs8", "pkcs1"] as const) {
      const pem = privateKey.export({ type, format: "pem" }).toString();
      expect(deriveLevel2KeyFromRsaGatewayInfo(wrapped(), pem)).toEqual(SESSION_KEY);
    }
  });

  test("answers undefined for a payload shorter than the modulus", () => {
    expect(deriveLevel2KeyFromRsaGatewayInfo(wrapped().subarray(0, 100), PKCS8_B64)).toBeUndefined();
  });

  test("answers undefined for key material that is not an RSA key", () => {
    expect(deriveLevel2KeyFromRsaGatewayInfo(wrapped(), "bm90IGEga2V5")).toBeUndefined();
    expect(deriveLevel2KeyFromRsaGatewayInfo(wrapped(), "")).toBeUndefined();
  });

  test("answers undefined under another RSA key", () => {
    const other = generateKeyPairSync("rsa", { modulusLength: 1024 }).privateKey;
    const otherB64 = other.export({ type: "pkcs8", format: "der" }).toString("base64");
    expect(deriveLevel2KeyFromRsaGatewayInfo(wrapped(), otherB64)).toBeUndefined();
  });

  test("answers undefined for a block that is not PKCS#1 v1.5 encryption padding", () => {
    const signaturePadded = Buffer.concat([
      Buffer.from([0x00, 0x01]),
      Buffer.alloc(109, 0xff),
      Buffer.from([0x00]),
      SESSION_KEY,
    ]);
    expect(deriveLevel2KeyFromRsaGatewayInfo(rawBlock(signaturePadded), PKCS8_B64)).toBeUndefined();
    const shortPad = Buffer.concat([
      Buffer.from([0x00, 0x02]),
      Buffer.alloc(7, 0x11),
      Buffer.from([0x00]),
      Buffer.alloc(118, 0x22),
    ]);
    expect(deriveLevel2KeyFromRsaGatewayInfo(rawBlock(shortPad), PKCS8_B64)).toBeUndefined();
  });

  /** `new String(plaintext)` handed to the native setter, which copies the string's first 16 bytes. */
  test("reads the wrapped key as the app does: the plaintext's first 16 bytes as a Java string, zero beyond it", () => {
    const nul = Buffer.concat([SESSION_KEY, Buffer.from([0x00])]);
    expect(deriveLevel2KeyFromRsaGatewayInfo(wrapped(nul), PKCS8_B64), "16 chars and a NUL").toEqual(SESSION_KEY);
    const long = Buffer.from("0123456789abcdef0123456789abcdef", "latin1");
    expect(deriveLevel2KeyFromRsaGatewayInfo(wrapped(long), PKCS8_B64), "32 chars").toEqual(SESSION_KEY);
    const short = Buffer.concat([Buffer.from("0123456789ab", "latin1"), Buffer.alloc(4)]);
    expect(deriveLevel2KeyFromRsaGatewayInfo(wrapped(Buffer.from("0123456789ab", "latin1")), PKCS8_B64)).toEqual(short);
    const leadingNul = Buffer.concat([Buffer.from([0xc0, 0x80, 0x41]), Buffer.alloc(13)]);
    expect(deriveLevel2KeyFromRsaGatewayInfo(wrapped(Buffer.from([0x00, 0x41])), PKCS8_B64), "NUL, A").toEqual(
      leadingNul,
    );
  });
});

type SessionInternals = {
  negotiateLevel2Key(payload: Buffer, version: number): void;
  handleFrame(header: unknown, payload: Buffer, dataType: number): void;
  connectAddress: unknown;
  send: (addr: unknown, type: Buffer, payload: Buffer) => void;
};

/** A session whose cipher answers an empty ECC key and the spec's RSA key, with its emitted events and traces. */
function rsaSession(stationSn = STATION_SN): {
  session: P2PSession;
  ready: unknown[];
  traces: ReturnType<typeof traceCollector>["traces"];
} {
  const { logger, traces } = traceCollector();
  const session = new P2PSession({
    stationSn,
    p2pDid: P2P_DID,
    logger,
    resolveCipherKey: async (cipherId, version) => (cipherId === CIPHER_ID && version !== 8 ? PKCS8_B64 : undefined),
  });
  const ready: unknown[] = [];
  session.on("level2Ready", (e) => ready.push(e));
  return { session, ready, traces };
}

/**
 * A session whose cipher answers both an ECC and the spec's RSA key, a feed of gateway-info frames by header
 * version, and a version-8 gateway info that unwraps under the ECC key.
 */
function dualSession(): ReturnType<typeof rsaSession> & {
  frame: (version: number, payload: Buffer) => void;
  v8: Buffer;
} {
  const ecdh = createECDH("prime256v1");
  ecdh.generateKeys();
  const { logger, traces } = traceCollector();
  const session = new P2PSession({
    stationSn: STATION_SN,
    p2pDid: P2P_DID,
    logger,
    resolveCipherKey: async (_cipherId, version) => (version === 8 ? ecdh.getPrivateKey("hex") : PKCS8_B64),
  });
  const ready: unknown[] = [];
  session.on("level2Ready", (e) => ready.push(e));
  const frame = (version: number, payload: Buffer) =>
    (session as unknown as SessionInternals).handleFrame(
      { commandId: 1100, bytesToRead: payload.length, version, channel: 0, signCode: 0, type: 0 },
      payload,
      2,
    );
  const head = Buffer.alloc(4);
  head.writeUInt16LE(CIPHER_ID, 0);
  const v8 = Buffer.concat([head, eciesWrap(Buffer.alloc(32, 7), ecdh.getPublicKey())]);
  return { session, ready, traces, frame, v8 };
}

/** {@link rsaSession}, negotiated from a gateway info. */
async function negotiatedSession(stationSn = STATION_SN): Promise<ReturnType<typeof rsaSession>> {
  const built = rsaSession(stationSn);
  (built.session as unknown as SessionInternals).negotiateLevel2Key(gatewayInfo(wrapped()), 1);
  await vi.waitFor(() => expect(built.session.hasLevel2Key).toBe(true));
  return built;
}

describe("P2PSession level-2 over an RSA cipher", () => {
  test("a cipher with no ECC key and an RSA key negotiates the level-2 key and announces it", async () => {
    const { session, ready, traces } = await negotiatedSession();
    expect(session.hasLevel2Key).toBe(true);
    expect(ready).toEqual([{ cipherId: CIPHER_ID }]);
    expect(traces.filter((trace) => trace.phase === "level2-ready")).toEqual([
      { phase: "level2-ready", cipherId: CIPHER_ID, source: session.traceId },
    ]);
  });

  /** The app's `NotifyInterceptor` picks the key by the header version, not by which key the cipher has. */
  test("a version-1 gateway info takes the RSA key even when the cipher also has an ECC key", async () => {
    const { logger, traces } = traceCollector();
    const session = new P2PSession({
      stationSn: STATION_SN,
      p2pDid: P2P_DID,
      logger,
      resolveCipherKey: async (_cipherId, version) => (version === 8 ? "11".repeat(32) : PKCS8_B64),
    });
    const errors: unknown[] = [];
    session.on("error", (e) => errors.push(e));
    const payload = gatewayInfo(wrapped());

    (session as unknown as SessionInternals).handleFrame(
      { commandId: 1100, bytesToRead: payload.length, version: 1, channel: 0, signCode: 0, type: 0 },
      payload,
      1,
    );

    await vi.waitFor(() => expect(session.hasLevel2Key).toBe(true));
    expect(errors).toEqual([]);
    expect(traces.filter((trace) => trace.phase === "level2-ready")).toHaveLength(1);
  });

  /** Each gateway info takes the session over in turn: a version-8 one after the RSA key ends on the ECC key. */
  test("a version-8 gateway info after a version-1 one still negotiates the ECC key", async () => {
    const { session, ready, frame, v8 } = dualSession();

    frame(1, gatewayInfo(wrapped()));
    await vi.waitFor(() => expect(session.hasLevel2Key).toBe(true));
    frame(8, v8);

    await vi.waitFor(() => expect(ready).toEqual([{ cipherId: CIPHER_ID }, { cipherId: CIPHER_ID }]));
    expect((session as unknown as { gcmKey?: Buffer }).gcmKey).toEqual(Buffer.alloc(32, 7));
  });

  /** The app handles every gateway info on its own, so a version-1 reply's lookup does not swallow the version-8 one. */
  test("a version-8 gateway info during a failing version-1 lookup negotiates the ECC key", async () => {
    const { session, ready, traces, frame, v8 } = dualSession();

    frame(1, gatewayInfo(Buffer.alloc(128, 0x33)));
    frame(8, v8);

    await vi.waitFor(() => expect(session.hasLevel2Key).toBe(true));
    expect(ready).toEqual([{ cipherId: CIPHER_ID }]);
    expect(traces.filter((trace) => trace.phase === "level2-negotiating").map((trace) => trace.version)).toEqual([
      1, 8,
    ]);
    expect(traces.filter((trace) => trace.phase === "level2-unavailable")).toEqual([]);
  });

  /**
   * The app's native step of a version-1 gateway info naming a cipher sets version 1 and sign mode 1 whatever the
   * session held, so one arriving after the version-8 key takes the session back to the level-1 key, and an RSA
   * unwrap that fails leaves it there.
   */
  test("a version-1 gateway info after the version-8 key takes the session back to sign mode 1", async () => {
    for (const settledFirst of [false, true]) {
      const { session, ready, traces, frame, v8 } = dualSession();
      const sent = capture(session);

      frame(8, v8);
      if (settledFirst) await vi.waitFor(() => expect(ready).toHaveLength(1));
      frame(1, gatewayInfo(Buffer.alloc(128, 0x33)));
      await vi.waitFor(() =>
        expect(traces.filter((trace) => trace.phase === "level2-unavailable")).toEqual([
          { phase: "level2-unavailable", reason: "derivation-failed", cipherId: CIPHER_ID, source: session.traceId },
        ]),
      );

      expect(ready).toEqual([{ cipherId: CIPHER_ID }]);
      expect(session.hasLevel2Key).toBe(false);
      session.sendBytes(Buffer.alloc(8, 0x11), 3, 1035);
      expect(sent.map(({ header }) => [header.version, header.signCode])).toEqual([[1, 1]]);
      expect(decryptP2PData(sent[0].body, Buffer.from(p2pCommandEncryptionKey(STATION_SN, P2P_DID)))).toEqual(
        paddingP2PData(Buffer.alloc(8, 0x11)),
      );
    }
  });

  test("an RSA key that does not unwrap the gateway info is traced and settled, not an error", async () => {
    const { session, traces } = rsaSession();
    const errors: unknown[] = [];
    session.on("error", (e) => errors.push(e));

    (session as unknown as SessionInternals).negotiateLevel2Key(gatewayInfo(Buffer.alloc(128, 0x33)), 1);

    await vi.waitFor(() => expect(traces.some((trace) => trace.phase === "level2-unavailable")).toBe(true));
    expect(session.hasLevel2Key).toBe(false);
    expect(errors).toEqual([]);
    expect(traces.find((trace) => trace.phase === "level2-negotiating")).toEqual({
      phase: "level2-negotiating",
      cipherId: CIPHER_ID,
      version: 1,
      source: session.traceId,
    });
    expect(traces.find((trace) => trace.phase === "level2-unavailable")).toEqual({
      phase: "level2-unavailable",
      reason: "derivation-failed",
      cipherId: CIPHER_ID,
      source: session.traceId,
    });
  });

  /** Sign mode 2 on a non-v8 session: AES-ECB under the session key, version byte 1, sign byte 2, for every send. */
  test("seals a direct scalar and a 1350 envelope AES-128-ECB at version byte 1 and sign byte 2", async () => {
    const { session } = await negotiatedSession();
    const sent = capture(session);
    const scalar = Buffer.alloc(8, 0x11);

    expect(session.sendBytes(scalar, 3, 1035)).toBe(true);
    session.sendFrame({ cmd: 1350, body: "json1350", subCmd: 1004, payload: { channel: "$channel" } }, 3, ACCOUNT_ID);
    session.sendSetPayload(2100, { isOpen: 1, userIndex: 0 }, { accountId: ACCOUNT_ID, channel: 0 });

    expect(sent.map(({ header }) => [header.commandId, header.version, header.signCode])).toEqual([
      [1035, 1, 2],
      [1350, 1, 2],
      [1350, 1, 2],
    ]);
    expect(decryptP2PData(sent[0].body, SESSION_KEY)).toEqual(paddingP2PData(scalar));
    const plainJson = (body: Buffer) =>
      JSON.parse(decryptP2PData(body, SESSION_KEY).toString("utf-8").replace(/\0+$/, ""));
    expect(plainJson(sent[1].body)).toEqual({
      account_id: ACCOUNT_ID,
      cmd: 1004,
      mChannel: 3,
      mValue3: 0,
      payload: { channel: 3 },
    });
    expect(plainJson(sent[2].body)).toEqual({
      account_id: ACCOUNT_ID,
      cmd: 2100,
      mChannel: 0,
      mValue3: 0,
      payload: { isOpen: 1, userIndex: 0 },
    });
  });

  test("opens a sign-2 reply AES-128-ECB under the session key", async () => {
    const { session } = await negotiatedSession();
    const frames: Array<{ data: Buffer }> = [];
    session.on("data", (frame) => frames.push(frame));
    const reply = paddingP2PData(Buffer.from('{"result":0}', "utf-8"));

    (session as unknown as SessionInternals).handleFrame(
      { commandId: 1350, bytesToRead: reply.length, version: 1, channel: 0, signCode: 2, type: 0 },
      encryptP2PData(reply, SESSION_KEY),
      0,
    );

    expect(frames.map((frame) => frame.data)).toEqual([reply]);
  });
});

/** Each payload a connected session sends, as the frame header and body that follow the 4-byte DATA prefix. */
function capture(session: P2PSession): Array<{ header: ReturnType<typeof parseDataFrameHeader>; body: Buffer }> {
  const internals = session as unknown as SessionInternals & { connected: boolean };
  const sent: Array<{ header: ReturnType<typeof parseDataFrameHeader>; body: Buffer }> = [];
  internals.connected = true;
  internals.connectAddress = { host: "127.0.0.1", port: 32100 };
  internals.send = (_addr, _type, payload) => {
    const frame = payload.subarray(4);
    sent.push({ header: parseDataFrameHeader(frame), body: frame.subarray(16) });
  };
  return sent;
}

/** On an RSA session the router sends every level-2 family under the session key, as on a GCM session. */
describe("routing on an RSA session", () => {
  it("sends a set-payload and a station scalar under the session key at sign byte 2", async () => {
    const { session } = await negotiatedSession(ROUTER_STATION_SN);
    const sent = capture(session);
    const internals = session as unknown as SessionInternals;
    const send = internals.send;
    internals.send = (addr, type, payload) => {
      send(addr, type, payload);
      const commandId = payload.readUInt16LE(8);
      queueMicrotask(() =>
        session.emit("commandResult", { code: 0, channel: commandId === 1350 ? 0 : 255, commandId }),
      );
    };
    const router = routerWithSession(session as unknown as FakeP2PSession);

    await onFakeTime(() =>
      router.dispatchCommand(DEVICE_SN, { kind: "set-payload", cmd: 1716, payload: { light_enable: 1 }, channel: 0 }),
    );
    await onFakeTime(() =>
      router.dispatchCommand(DEVICE_SN, { kind: "p2p-station-scalar", cmd: 1235, value: 1, channel: 255 }),
    );

    expect(sent.map(({ header }) => [header.commandId, header.version, header.signCode])).toEqual([
      [1350, 1, 2],
      [1235, 1, 2],
    ]);
  });
});

/** The app's notify thread reads nothing on channel 2 while a gateway info's key lookup blocks it. */
describe("P2PSession channel 2 during a gateway key lookup", () => {
  test("holds channel-2 frames until the key step ends, then delivers them in order; other channels flow", async () => {
    let answer!: (key: string | undefined) => void;
    const session = new P2PSession({
      stationSn: STATION_SN,
      p2pDid: P2P_DID,
      resolveCipherKey: () => new Promise((resolve) => (answer = resolve)),
    });
    const seen: number[] = [];
    session.on("data", (frame: { commandId: number }) => seen.push(frame.commandId));
    const handle = (session as unknown as SessionInternals).handleFrame.bind(session);
    const notify = (commandId: number, dataType: number) =>
      handle({ commandId, bytesToRead: 2, version: 1, channel: 0, signCode: 0, type: 0 }, Buffer.from("{}"), dataType);

    handle(
      { commandId: 1100, bytesToRead: 132, version: 1, channel: 0, signCode: 0, type: 0 },
      gatewayInfo(wrapped()),
      2,
    );
    notify(1351, 2);
    notify(1103, 2);
    notify(1306, 0);
    expect(seen).toEqual([1100, 1306]);

    answer(undefined);
    await vi.waitFor(() => expect(seen).toEqual([1100, 1306, 1351, 1103]));
  });
});
